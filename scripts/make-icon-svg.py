#!/usr/bin/env python3
"""
filo - writes build-resources/icon.svg: the word "filo" in Poppins Bold, the
letters turned into vector outlines (so the icon does not depend on the font
being installed), "fil" in white and the "o" in filo's turquoise #19C9B4 (Noar, 12/10/2026;
FileZilla's red #BF0000 until 0.6.1, too close to Presto's magenta), on
the family's black square (824 px on 1024, corner radius 185).

Needs: pip install fonttools
Then:  python3 scripts/gen-icons.py   (PNG / ICO / ICNS from the SVG)
"""
import os
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen

HERE = os.path.dirname(os.path.abspath(__file__))
FONT = os.path.join(HERE, "..", "src", "renderer", "fonts", "Poppins-Bold.ttf")
OUT = os.path.join(HERE, "..", "build-resources", "icon.svg")
RED = "#19C9B4"   # filo's turquoise (the name RED is historical)

font = TTFont(FONT)
gs = font.getGlyphSet()
cmap = font.getBestCmap()
hmtx = font["hmtx"]

word = "filo"
x = 0
parts = []
bounds = BoundsPen(gs)
for ch in word:
    name = cmap[ord(ch)]
    pen = SVGPathPen(gs)
    gs[name].draw(pen)
    parts.append((ch, pen.getCommands(), x))
    # bounds of the whole word, shifted to this letter
    bp = BoundsPen(gs)
    gs[name].draw(bp)
    if bp.bounds:
        b = bp.bounds
        bounds.bounds = (b[0] + x, b[1], b[2] + x, b[3]) if bounds.bounds is None else (
            min(bounds.bounds[0], b[0] + x), min(bounds.bounds[1], b[1]),
            max(bounds.bounds[2], b[2] + x), max(bounds.bounds[3], b[3]))
    x += hmtx[name][0]

xmin, ymin, xmax, ymax = bounds.bounds
w, h = xmax - xmin, ymax - ymin
# Fit the word in 640 px wide, centred in the 1024 canvas (font units have y up).
scale = 640.0 / w
tx = 512 - (xmin + w / 2) * scale
ty = 512 + (ymin + h / 2) * scale

paths = []
for ch, d, dx in parts:
    colour = RED if ch == "o" else "#ffffff"
    paths.append(f'  <path transform="translate({tx + dx * scale:.2f} {ty:.2f}) scale({scale:.5f} {-scale:.5f})" d="{d}" fill="{colour}"/>')

svg = f'''<?xml version="1.0" encoding="UTF-8"?>
<!--
  filo - app icon (0.1.0, asked by Noar on 09.10.2026).

  The word "filo" in Poppins Bold, as outlines; only the "o" in colour, filo's
  turquoise #19C9B4 (until 0.6.1: FileZilla's red #BF0000). Family template (syncto, ingesto...): black
  square, white drawing, ONE element in the application's colour. Shape 824 px
  on a 1024 canvas, corner radius 185 (Apple template).

  Generated by scripts/make-icon-svg.py - edit that script, not this file.
-->
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <rect x="100" y="100" width="824" height="824" rx="185" fill="#000000"/>
{chr(10).join(paths)}
</svg>
'''
open(OUT, "w").write(svg)
print("icon.svg written")
